export function getAllCurrencies(): CurrencyItem[] {
  const map = new Map<string, CurrencyItem>();

  for (const country of COUNTRIES) {
    const existing = map.get(country.currencyCode);
    if (!existing) {
      map.set(country.currencyCode, {
        code: country.currencyCode,
        name: country.currency,
        symbol: SYMBOL_MAP[country.currencyCode] || country.currencyCode,
        countries: [{ name: country.name, flag: country.flag, code: country.code }],
        regions: [country.region],
      });
    } else {
      existing.countries.push({
        name: country.name,
        flag: country.flag,
        code: country.code,
      });
      if (!existing.regions.includes(country.region)) {
        existing.regions.push(country.region);
      }
    }
  }

  return Array.from(map.values()).sort((a, b) => a.code.localeCompare(b.code));
}

export const ALL_CURRENCIES = getAllCurrencies();
